"""
Description
This Python script renders an academic-grade heatmap visualization of the Stratified 5-Fold Cross-Validation evaluation matrix for the Random Forest classifier. It loads folded performance metrics (Accuracy, Error Rate E_k, Precision, Recall, and F_1-Score) from Stratified_5Fold_CV_Matrix.csv, dynamically formats metric labels, and exports publication-ready high-resolution raster (Stratified_5Fold_CV_Heatmap.png) and vector graphics (Stratified_5Fold_CV_Heatmap.pdf) assets.
"""
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path

# Set academic design style
plt.style.use("seaborn-v0_8-paper" if "seaborn-v0_8-paper" in plt.style.available else "default")
plt.rcParams["font.family"] = "sans-serif"
plt.rcParams["font.size"] = 11

# ==========================================
# 1. LOAD MATRIX DATA
# ==========================================
result_sheet3_dir = Path(r"C:\Users\User\Documents\RFExplorer\Result_Sheet3")
csv_path = result_sheet3_dir / "Stratified_5Fold_CV_Matrix.csv"

# Load matrix data generated by the cross-validation run
df_matrix = pd.read_csv(csv_path, index_col=0)

# Select performance metrics for visualization (excluding sample counts)
metrics = ["Fold Accuracy (%)", "Error Rate E_k (%)", "Precision (%)", "Recall (%)", "F1-Score"]
df_plot = df_matrix[metrics].copy()

# ==========================================
# 2. GENERATE HEATMAP
# ==========================================
fig, ax = plt.subplots(figsize=(10, 6), dpi=300)

# Custom text annotation formatter (handles both percentages and decimals cleanly)
annot_matrix = np.empty(df_plot.shape, dtype=object)
for i in range(df_plot.shape[0]):
    for j in range(df_plot.shape[1]):
        val = df_plot.iloc[i, j]
        col_name = df_plot.columns[j]
        if "F1" in col_name:
            annot_matrix[i, j] = f"{val:.4f}"
        elif "Error" in col_name:
            annot_matrix[i, j] = f"{val:.3f}%"
        else:
            annot_matrix[i, j] = f"{val:.2f}%"

sns.heatmap(
    df_plot,
    annot=annot_matrix,
    fmt="",
    cmap="YlGnBu",
    cbar_kws={'label': 'Metric Value / Percentage'},
    linewidths=1.5,
    linecolor='white',
    ax=ax,
    annot_kws={"size": 11, "weight": "bold"}
)

# Customize Axes and Labels
ax.set_title("Stratified 5-Fold Cross-Validation Performance Matrix", fontsize=14, weight="bold", pad=15)
ax.set_xlabel("Evaluation Metrics", fontsize=12, weight="bold", labelpad=10)
ax.set_ylabel("Fold Iterations", fontsize=12, weight="bold", labelpad=10)

plt.xticks(rotation=15, ha="right")
plt.yticks(rotation=0)
plt.tight_layout()

# ==========================================
# 3. SAVE HIGH-RES FIGURES
# ==========================================
png_out = result_sheet3_dir / "Stratified_5Fold_CV_Heatmap.png"
pdf_out = result_sheet3_dir / "Stratified_5Fold_CV_Heatmap.pdf"

plt.savefig(png_out, dpi=300, bbox_inches="tight")
plt.savefig(pdf_out, format="pdf", bbox_inches="tight")

print(f"[✓] Heatmap generated and saved successfully to:\n    {png_out}")
plt.show()
